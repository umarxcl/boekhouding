#!/usr/bin/env python3
"""Generate the recurring month-end adjusting entries for XCL into xcl/2026/month_end.beancount.

Per month (entry dated on the last day of the month):
  1. Salary accrual per the contract (Expenses:Staff:Salary-Umar / Liabilities:Employees:SalaryPayable-Umar),
     pro rata per calendar day when the salary changes or the contract starts mid-month.
  2. End-of-service benefit accrual (Expenses:Staff:EndOfService / Liabilities:Employees:EndOfService).
  3. Private share of the car costs (Assets:Receivables:Director:Umar / Expenses:Car:*).

Not generated (see docs/runbook.md section 9): set-off of the director's current account against the salary
payable (needs the signed addendum), leave accrual (needs leave days taken), FX revaluation (needs the CBUAE rate).

The whole file is regenerated each time (deterministic). Usage:
    python3 scripts/month_end.py --through 2026-10            # write the file
    python3 scripts/month_end.py --through 2026-10 --check    # only compare with the file on disk
"""
import argparse
import calendar
import datetime as dt
import sys
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

import yaml
from beancount import loader
from beancount.core import data

ROOT = Path(__file__).resolve().parent.parent
LEDGER = ROOT / "xcl" / "main.beancount"
PARAMS = ROOT / "xcl" / "parameters.yaml"
OUT = ROOT / "xcl" / "2026" / "month_end.beancount"
GENERATED = "month_end"
CENT = Decimal("0.01")


def q(x):
    return Decimal(x).quantize(CENT, rounding=ROUND_HALF_UP)


def fmt(x):
    return f"{q(x):,.2f}"


def months(start, through):
    y, m = start.year, start.month
    while (y, m) <= (through.year, through.month):
        yield y, m
        m += 1
        if m == 13:
            y, m = y + 1, 1


def salary_for_month(periods, y, m):
    """Salary for the month, pro rata per calendar day over the periods that apply."""
    dim = calendar.monthrange(y, m)[1]
    total = Decimal(0)
    for d in range(1, dim + 1):
        day = dt.date(y, m, d)
        applicable = [p for p in periods if p["from"] <= day]
        if applicable:
            total += Decimal(str(applicable[-1]["monthly"])) / dim
    return q(total)


def car_costs(entries, y, m):
    """AED cost per Expenses:Car:* account in the month, excluding the generated entries."""
    sums = {}
    for e in entries:
        if not isinstance(e, data.Transaction) or (e.date.year, e.date.month) != (y, m):
            continue
        if e.meta.get("generated") == GENERATED:
            continue
        for p in e.postings:
            if p.account.startswith("Expenses:Car:") and p.units.currency == "AED":
                sums[p.account] = sums.get(p.account, Decimal(0)) + p.units.number
    return sums


def build(through):
    params = yaml.safe_load(PARAMS.read_text())
    salary = sorted(params["salary"], key=lambda p: p["from"])
    shares = sorted(params["car_private_share"], key=lambda p: p["from"])
    eosb = params["eosb"]
    entries, errors, _ = loader.load_file(str(LEDGER))
    entries = [e for e in entries if not (isinstance(e, data.Transaction) and e.meta.get("generated") == GENERATED)]
    out = [
        "; GENERATED by scripts/month_end.py from xcl/parameters.yaml and the bank entries. Do not edit by hand.",
        "; Recurring month-end adjusting entries: salary accrual, end-of-service accrual, private share of car costs.",
        "",
    ]
    start = salary[0]["from"]
    for y, m in months(start, through):
        last = dt.date(y, m, calendar.monthrange(y, m)[1])
        sal = salary_for_month(salary, y, m)
        if sal > 0:
            out += [
                f'{last} * "Salary accrual" "Contract salary {y}-{m:02d}"',
                f'  generated: "{GENERATED}"',
                '  basis: "Employment contract 18-12-2025, basic salary per month, pro rata per calendar day; xcl/parameters.yaml"',
                f"  Expenses:Staff:Salary-Umar                    {fmt(sal)} AED",
                f"  Liabilities:Employees:SalaryPayable-Umar     {fmt(-sal)} AED",
                "",
            ]
            e_amt = q(sal * Decimal(eosb["days_per_year"]) / Decimal(eosb["day_divisor"]) / 12)
            out += [
                f'{last} * "End-of-service accrual" "End-of-service benefit {y}-{m:02d}"',
                f'  generated: "{GENERATED}"',
                f'  basis: "{eosb["days_per_year"]} days of basic salary per year, daily rate = monthly salary / {eosb["day_divisor"]}; accrued from day one"',
                f"  Expenses:Staff:EndOfService                   {fmt(e_amt)} AED",
                f"  Liabilities:Employees:EndOfService           {fmt(-e_amt)} AED",
                "",
            ]
        applicable = [s for s in shares if s["from"] <= last]
        if applicable:
            share = Decimal(str(applicable[-1]["share"]))
            costs = car_costs(entries, y, m)
            parts = {a: q(v * share) for a, v in sorted(costs.items()) if q(v * share) != 0}
            total = sum(parts.values(), Decimal(0))
            if total != 0:
                lines = [
                    f'{last} * "Car costs private share" "Private share {int(share * 100)}% of car costs {y}-{m:02d}"',
                    f'  generated: "{GENERATED}"',
                    '  basis: "Decision Umar 2-11-2026: 30% private via the director current account (debt route, no benefit in kind)"',
                    f"  Assets:Receivables:Director:Umar              {fmt(total)} AED",
                ]
                for a, v in parts.items():
                    lines.append(f"  {a:<45} {fmt(-v)} AED")
                out += lines + [""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--through", required=True, help="last month to include, YYYY-MM")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    y, m = map(int, a.through.split("-"))
    text = build(dt.date(y, m, 1))
    if a.check:
        same = OUT.exists() and OUT.read_text() == text
        print("month_end.beancount: " + ("up to date" if same else "DIFFERS from generator"))
        sys.exit(0 if same else 1)
    OUT.write_text(text)
    print(f"Written: {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
